missing: list[str] = []
changed = 0
for old, new in REPLACEMENTS.items():
    if old in html:
        html = html.replace(old, new)
        changed += 1
    else:
        missing.append(old)

# The stats are already visible in the hero. Keep the review section focused on quotes.
review_proof_re = re.compile(
    r'<div class="s113-review-proof">\s*<strong>20 отзывов в профиле</strong>\s*'
    r'<span>Профессионализм 9/10 · коммуникация 9/10 · опыт 6 лет</span>\s*'
    r'<a href="https://freelance\.ru/reviews/gglalex/"[^>]*>Открыть все отзывы ↗</a>\s*</div>',
    re.S,
)
